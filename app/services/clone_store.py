"""Durable storage for clones, consent records, provenance manifests and audit.

Everything a clone needs lives in one directory tree (``CLONE_STORE_DIR``):

``registry.json``
    Voice entries.  Written atomically; loaded tolerantly, because a corrupt
    consent store must degrade to "no clones" rather than stop the service from
    booting (the same tolerance the designed-voice store already has).
``voices/<id>/consent.json``
    The signed consent record, stored **beside** the voice it authorises
    (ADR-0003 #2).
``voices/<id>/embedding.enc``
    The derived speaker embedding, encrypted under the reference key.  The
    reference clip is deleted by default, so the clone must be re-derivable from
    this artefact alone.
``voices/<id>/reference.wav.enc``
    Only present when retention was explicitly requested.  This is a visible
    exception on the consent record, capped at 90 days.
``manifests.json``
    The provenance registry.  A **durable store**, deliberately not bounded by
    the reference-retention ceiling: a manifest records that a file was made and
    must outlive the voice.
``audit.jsonl``
    Append-only audit trail for create, use and takedown.
"""

from __future__ import annotations

import json
import logging
import os
import re
import tempfile
import threading
import time
from collections import OrderedDict
from pathlib import Path
from typing import Any, Callable

from app.services import clone_crypto

logger = logging.getLogger(__name__)

#: Prefix every generated clone id carries.  A synthesis request for an id with
#: this prefix and no record fails closed (410) instead of falling back to
#: another voice.
CLONE_ID_PREFIX = "clone_"

#: The scope enumeration from ADR-0003 #6.  Recorded, never enforced here.
SCOPES: tuple[str, ...] = (
    "internal-only",
    "customer-facing-approved",
    "demo",
    "sandbox",
)

#: Fields a consent record must carry before a clone may be created.
REQUIRED_CONSENT_FIELDS: tuple[str, ...] = (
    "subjectName",
    "purpose",
    "capturedAt",
    "expiresAt",
    "approver",
    "evidence",
    "scope",
)

#: Hard ceiling on reference retention, independent of consent expiry.
MAX_REFERENCE_RETENTION_DAYS = 90

SCHEMA_VERSION = 1

#: Bounded in-memory cache of decrypted embeddings.  Synthesis is the hot path
#: and must not re-decrypt (let alone re-extract) on every request.
MAX_EMBEDDING_CACHE_ENTRIES = 64


class CloneStoreError(RuntimeError):
    """The clone store could not be written."""


#: Characters a clone id may contain.  Ids are generated by the service as
#: ``clone_<slug>_<hex>`` and are the only thing ever interpolated into a store
#: path, so the shape can be stated exactly.  Anything else — a separator, ``..``,
#: a NUL, an absolute path — is rejected before it reaches the filesystem.
CLONE_ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]{0,127}$")


class InvalidVoiceId(ValueError):
    """A voice id is not a well-formed clone id and cannot name a store path.

    Raised **before** any path is built, so an id chosen by a caller can never
    escape the store root.  This is a caller error (HTTP 400/404), not a store
    failure.
    """


def validate_voice_id(voice_id: str | None) -> str:
    """Return ``voice_id`` if it is a safe store-path component, else raise.

    Two checks, and both matter:

    * ``os.path.basename()`` derives the path component.  If the value carries any
      directory part — ``a/b``, ``/etc/passwd``, ``a/``, ``a/.`` — basename strips
      it and ``component == raw`` fails.  This is the shape the path-injection
      query understands as an allow-list barrier, and it is why the sanitised
      value is what this function returns and what every caller then uses.
    * ``CLONE_ID_PATTERN.fullmatch()``, not ``.match()``.  ``$`` also matches just
      before a trailing newline, so ``"clone_x\n"`` used to pass ``.match()``.  A
      trailing newline in an id reaches a filename and, worse, a log line.

    Defence in depth: Starlette will not match a ``/`` inside a single path
    segment, and most callers reach the filesystem only after a registry lookup,
    but ``CloneStore`` is a service-level API and must not depend on that
    discipline.
    """
    raw = "" if voice_id is None else str(voice_id)
    component = os.path.basename(raw)
    if component != raw or not CLONE_ID_PATTERN.fullmatch(component):
        raise InvalidVoiceId(
            f"Invalid voice id {raw!r}: a clone id must fully match "
            f"{CLONE_ID_PATTERN.pattern} (no separators, no '..', no absolute "
            "paths, no trailing newline)."
        )
    return component


def is_clone_id(value: str | None) -> bool:
    return bool(value) and str(value).startswith(CLONE_ID_PREFIX)


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=path.suffix)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except OSError:  # pragma: no cover - best effort cleanup
            pass
        raise


class CloneStore:
    """Thread-safe, file-backed store for the clone governance artefacts."""

    def __init__(
        self,
        root: str | Path,
        *,
        reference_key: bytes | None = None,
        clock: Callable[[], float] = time.time,
    ) -> None:
        self.root = Path(root)
        self._registry_path = self.root / "registry.json"
        self._manifests_path = self.root / "manifests.json"
        self._audit_path = self.root / "audit.jsonl"
        self._reference_key = reference_key
        self._clock = clock
        self._lock = threading.RLock()
        self._entries: dict[str, dict[str, Any]] = {}
        self._manifests: dict[str, dict[str, Any]] = {}
        self._embedding_cache: OrderedDict[str, bytes] = OrderedDict()
        #: Number of times an embedding had to be read from disk and decrypted.
        #: Tests assert repeated synthesis does not increment it.
        self.embedding_reads = 0
        self.load()

    # ------------------------------------------------------------------
    # Loading (tolerant by design)
    # ------------------------------------------------------------------

    def load(self) -> None:
        with self._lock:
            self._entries = {}
            self._manifests = {}
            self._embedding_cache.clear()
            self._load_registry()
            self._load_manifests()

    def _load_registry(self) -> None:
        try:
            text = self._registry_path.read_text(encoding="utf-8")
        except FileNotFoundError:
            return
        except OSError as exc:
            logger.warning(
                "Clone registry %s could not be read (%s); continuing with NO clones.",
                self._registry_path,
                exc,
            )
            return
        try:
            payload = json.loads(text)
        except json.JSONDecodeError as exc:
            logger.warning(
                "Clone registry %s is not valid JSON (%s); continuing with NO clones. "
                "Cloning degrades to unavailable rather than failing to boot.",
                self._registry_path,
                exc,
            )
            return
        entries = payload.get("voices") if isinstance(payload, dict) else None
        if not isinstance(entries, list):
            logger.warning(
                "Clone registry %s has no 'voices' list; continuing with NO clones.",
                self._registry_path,
            )
            return
        for entry in entries:
            if not isinstance(entry, dict) or not entry.get("id"):
                logger.warning("Skipping malformed clone entry in %s.", self._registry_path)
                continue
            self._entries[str(entry["id"])] = dict(entry)
        logger.info("Loaded %d clone(s) from %s.", len(self._entries), self._registry_path)

    def _load_manifests(self) -> None:
        try:
            payload = json.loads(self._manifests_path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return
        except (OSError, json.JSONDecodeError) as exc:
            # Losing provenance records is serious, but refusing to boot does not
            # recover them; the operator sees this warning and the backup.
            logger.warning(
                "Provenance manifest registry %s could not be read (%s); provenance "
                "lookups will report 'no record found' until it is restored.",
                self._manifests_path,
                exc,
            )
            return
        manifests = payload.get("manifests") if isinstance(payload, dict) else None
        if isinstance(manifests, dict):
            self._manifests = {
                str(key): dict(value)
                for key, value in manifests.items()
                if isinstance(value, dict)
            }

    # ------------------------------------------------------------------
    # Registry
    # ------------------------------------------------------------------

    @property
    def registry_path(self) -> Path:
        return self._registry_path

    def _confine(self, path: Path, voice_id: str) -> Path:
        """Return ``path`` resolved and proven to live under the store root.

        ``os.path.realpath`` + a ``root + os.sep`` prefix test is the canonical
        containment check: it normalises ``..`` segments *and* follows symlinks, so
        a symlinked store entry cannot redirect a read or an unlink outside the
        root.  The checked string is what gets returned and used, so no caller can
        accidentally keep the unnormalised original.

        Written this way rather than with ``Path.resolve()`` and
        ``is_relative_to()`` because static analysis models ``realpath`` and a
        ``startswith`` guard as a sanitising barrier and does not model the pathlib
        equivalents — the runtime guarantee was already correct, but an unmodelled
        guard leaves the alert open and hides the next real one.
        """
        root = os.path.realpath(self.root)
        resolved = os.path.realpath(path)
        if not resolved.startswith(root + os.sep):
            raise InvalidVoiceId(
                f"Refusing to use a path outside the clone store for id {voice_id!r}."
            )
        return Path(resolved)

    def voice_dir(self, voice_id: str) -> Path:
        """The directory holding one clone's artefacts.

        The id is validated before it is joined, so ``../`` and separators cannot
        address anything outside ``root/voices``.
        """
        return self._confine(self.root / "voices" / validate_voice_id(voice_id), voice_id)

    def consent_path(self, voice_id: str) -> Path:
        return self.voice_dir(voice_id) / "consent.json"

    def embedding_path(self, voice_id: str) -> Path:
        return self.voice_dir(voice_id) / "embedding.enc"

    def reference_path(self, voice_id: str) -> Path:
        return self.voice_dir(voice_id) / "reference.wav.enc"

    def get(self, voice_id: str | None) -> dict[str, Any] | None:
        if not voice_id:
            return None
        with self._lock:
            entry = self._entries.get(voice_id)
            return dict(entry) if entry is not None else None

    def entries(self) -> list[dict[str, Any]]:
        with self._lock:
            return [dict(entry) for entry in self._entries.values()]

    def add(self, entry: dict[str, Any]) -> dict[str, Any]:
        voice_id = str(entry["id"])
        with self._lock:
            if voice_id in self._entries:
                raise CloneStoreError(f"clone id {voice_id} already exists")
            entries = dict(self._entries)
            entries[voice_id] = dict(entry)
            self._write_registry(entries)
            self._entries = entries
            return dict(entry)

    def update(self, voice_id: str, **fields: Any) -> dict[str, Any]:
        with self._lock:
            current = self._entries.get(voice_id)
            if current is None:
                raise KeyError(voice_id)
            entry = {**current, **fields}
            entries = dict(self._entries)
            entries[voice_id] = entry
            self._write_registry(entries)
            self._entries = entries
            return dict(entry)

    def remove(self, voice_id: str) -> dict[str, Any] | None:
        with self._lock:
            entry = self._entries.get(voice_id)
            if entry is None:
                return None
            entries = dict(self._entries)
            entries.pop(voice_id, None)
            self._write_registry(entries)
            self._entries = entries
            self._embedding_cache.pop(voice_id, None)
            return dict(entry)

    def _write_registry(self, entries: dict[str, dict[str, Any]]) -> None:
        payload = {
            "schema_version": SCHEMA_VERSION,
            "description": (
                "Consent-gated voice clones. Consent records and encrypted embeddings "
                "live beside each entry under voices/<id>/."
            ),
            "voices": list(entries.values()),
        }
        try:
            _atomic_write(
                self._registry_path,
                (json.dumps(payload, indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
            )
        except OSError as exc:
            raise CloneStoreError(f"could not write the clone registry: {exc}") from exc

    # ------------------------------------------------------------------
    # Consent record (beside the voice)
    # ------------------------------------------------------------------

    def write_consent(self, voice_id: str, record: dict[str, Any]) -> Path:
        path = self.consent_path(voice_id)
        try:
            _atomic_write(
                path,
                (json.dumps(record, indent=2, ensure_ascii=True) + "\n").encode("utf-8"),
            )
        except OSError as exc:
            raise CloneStoreError(f"could not write the consent record: {exc}") from exc
        return path

    def read_consent(self, voice_id: str) -> dict[str, Any] | None:
        """Read a consent record, or ``None`` when there is none.

        An id that cannot name a store path is treated as "no record" rather than
        raising: this is called with a raw request-path id from the consent
        endpoint, and a malformed id is indistinguishable from an unknown one to
        that caller.
        """
        try:
            path = self.consent_path(voice_id)
        except InvalidVoiceId:
            # Deliberately does not echo the rejected value: it is caller-supplied
            # and would let a crafted id write a line into the log.
            logger.warning("Refusing a consent lookup for a malformed voice id.")
            return None
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (FileNotFoundError, OSError, json.JSONDecodeError):
            return None
        return payload if isinstance(payload, dict) else None

    # ------------------------------------------------------------------
    # Encrypted artefacts
    # ------------------------------------------------------------------

    def write_reference(self, voice_id: str, plaintext: bytes) -> Path:
        """Encrypt and persist reference audio under the separate reference key."""
        if self._reference_key is None:
            raise clone_crypto.KeyMaterialError("the reference-audio key is not configured")
        blob = clone_crypto.encrypt(
            self._reference_key, plaintext, aad=voice_id.encode("utf-8")
        )
        path = self.reference_path(voice_id)
        try:
            _atomic_write(path, blob)
        except OSError as exc:
            raise CloneStoreError(f"could not write encrypted reference audio: {exc}") from exc
        return path

    def read_reference(self, voice_id: str) -> bytes | None:
        """Decrypt and return the retained reference audio, or ``None``."""
        if self._reference_key is None:
            return None
        try:
            blob = self.reference_path(voice_id).read_bytes()
        except OSError:
            return None
        return clone_crypto.decrypt(
            self._reference_key, blob, aad=voice_id.encode("utf-8")
        )

    def write_embedding(self, voice_id: str, plaintext: bytes) -> Path:
        if self._reference_key is None:
            raise clone_crypto.KeyMaterialError("the reference-audio key is not configured")
        blob = clone_crypto.encrypt(
            self._reference_key, plaintext, aad=f"embedding:{voice_id}".encode("utf-8")
        )
        path = self.embedding_path(voice_id)
        try:
            _atomic_write(path, blob)
        except OSError as exc:
            raise CloneStoreError(f"could not write the embedding: {exc}") from exc
        with self._lock:
            self._embedding_cache[voice_id] = plaintext
            self._embedding_cache.move_to_end(voice_id)
            while len(self._embedding_cache) > MAX_EMBEDDING_CACHE_ENTRIES:
                self._embedding_cache.popitem(last=False)
        return path

    def load_embedding(self, voice_id: str) -> bytes:
        """Return the embedding, decrypting only on the first access.

        The reference clip is gone by default, so this is the only artefact a
        synthesis can be derived from.
        """
        with self._lock:
            cached = self._embedding_cache.get(voice_id)
            if cached is not None:
                self._embedding_cache.move_to_end(voice_id)
                return cached
        if self._reference_key is None:
            raise clone_crypto.KeyMaterialError("the reference-audio key is not configured")
        try:
            blob = self.embedding_path(voice_id).read_bytes()
        except FileNotFoundError as exc:
            raise CloneStoreError(
                f"clone {voice_id} has no embedding; it cannot be re-derived without one "
                "(the reference clip is deleted by default)"
            ) from exc
        plaintext = clone_crypto.decrypt(
            self._reference_key, blob, aad=f"embedding:{voice_id}".encode("utf-8")
        )
        with self._lock:
            self.embedding_reads += 1
            self._embedding_cache[voice_id] = plaintext
            self._embedding_cache.move_to_end(voice_id)
            while len(self._embedding_cache) > MAX_EMBEDDING_CACHE_ENTRIES:
                self._embedding_cache.popitem(last=False)
        return plaintext

    def delete_reference(self, voice_id: str) -> bool:
        """Delete retained reference audio.  **Succeeds when it is already gone.**"""
        path = self.reference_path(voice_id)
        try:
            path.unlink()
            return True
        except FileNotFoundError:
            return False
        except OSError:  # pragma: no cover - environmental
            # Nothing derived from the request reaches the log: both the path and
            # the id can carry caller-supplied text, and an embedded newline would
            # forge a log line. The id is recorded in the audit log, which is the
            # place built for it.
            logger.warning("Could not delete retained reference audio.")
            return False

    def delete_artefacts(self, voice_id: str, preview_dir: str | Path | None = None) -> list[str]:
        """Remove audio, embedding and any preview, tolerating missing files.

        The id is validated once, up front, so every derived path — including the
        preview outside the store root — is built from a checked component.
        """
        safe_id = validate_voice_id(voice_id)
        removed: list[str] = []
        paths = [
            self.reference_path(safe_id),
            self.embedding_path(safe_id),
            self.voice_dir(safe_id) / f"{safe_id}.wav",
        ]
        if preview_dir is not None:
            paths.append(Path(preview_dir) / f"{safe_id}.wav")
        for path in paths:
            try:
                path.unlink()
                removed.append(str(path))
            except FileNotFoundError:
                continue
            except OSError:  # pragma: no cover - environmental
                # Constant message: the artefact path is built from a caller-supplied
                # id and must not reach the log (see delete_reference).
                logger.warning("Could not delete one clone artefact.")
        with self._lock:
            self._embedding_cache.pop(voice_id, None)
        return removed

    # ------------------------------------------------------------------
    # Provenance manifests (durable; outlives the voice)
    # ------------------------------------------------------------------

    def register_manifest(self, manifest: dict[str, Any]) -> dict[str, Any]:
        """Store a manifest, keyed by ``audioSha256``.

        Re-registering identical audio returns the existing manifest: the
        creation time then truthfully records when that file was first made.
        """
        digest = str(manifest.get("audioSha256") or "")
        if not digest:
            raise CloneStoreError("a manifest needs audioSha256")
        with self._lock:
            existing = self._manifests.get(digest)
            if existing is not None:
                # The registry is keyed by the hash the verification path
                # computes, because a caller holding a file does not know which
                # voice made it.  That makes bit-identical PCM from two different
                # voices genuinely ambiguous: the file could be either.  Say so
                # rather than silently attributing it to the first clone.
                if str(existing.get("voiceId")) != str(manifest.get("voiceId")):
                    logger.warning(
                        "Provenance digest %s was produced by more than one voice "
                        "(%s and %s); a lookup for it cannot say which. The first "
                        "record is returned.",
                        digest,
                        existing.get("voiceId"),
                        manifest.get("voiceId"),
                    )
                return dict(existing)
            manifests = dict(self._manifests)
            manifests[digest] = dict(manifest)
            payload = {
                "schema_version": SCHEMA_VERSION,
                "description": (
                    "Signed provenance manifests keyed by SHA-256 of decoded PCM. A durable "
                    "store: retention is deliberately not bounded by reference retention."
                ),
                "manifests": manifests,
            }
            try:
                _atomic_write(
                    self._manifests_path,
                    (json.dumps(payload, indent=2, ensure_ascii=True) + "\n").encode("utf-8"),
                )
            except OSError as exc:
                raise CloneStoreError(f"could not write the manifest registry: {exc}") from exc
            self._manifests = manifests
            return dict(manifest)

    def get_manifest(self, digest: str) -> dict[str, Any] | None:
        with self._lock:
            manifest = self._manifests.get(digest)
            return dict(manifest) if manifest is not None else None

    def manifests_for_voice(self, voice_id: str) -> list[dict[str, Any]]:
        with self._lock:
            return [
                dict(manifest)
                for manifest in self._manifests.values()
                if manifest.get("voiceId") == voice_id
            ]

    def manifest_count(self) -> int:
        with self._lock:
            return len(self._manifests)

    # ------------------------------------------------------------------
    # Audit (append-only, never contains audio or hashes that could match it)
    # ------------------------------------------------------------------

    def audit(self, action: str, **fields: Any) -> dict[str, Any]:
        entry: dict[str, Any] = {
            "at": format_timestamp(self._clock()),
            "action": action,
        }
        for key, value in fields.items():
            if value is not None:
                entry[key] = value
        with self._lock:
            self._audit_path.parent.mkdir(parents=True, exist_ok=True)
            try:
                with self._audit_path.open("a", encoding="utf-8") as handle:
                    handle.write(json.dumps(entry, sort_keys=True, ensure_ascii=True) + "\n")
                    handle.flush()
                    os.fsync(handle.fileno())
            except OSError as exc:  # pragma: no cover - environmental
                logger.error("Could not append to the clone audit log: %s", exc)
        return entry

    def read_audit(self) -> list[dict[str, Any]]:
        try:
            lines = self._audit_path.read_text(encoding="utf-8").splitlines()
        except (FileNotFoundError, OSError):
            return []
        entries: list[dict[str, Any]] = []
        for line in lines:
            try:
                payload = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(payload, dict):
                entries.append(payload)
        return entries

    # ------------------------------------------------------------------
    # Retention
    # ------------------------------------------------------------------

    # Retention enforcement lives in VoiceCloneService._purge_expired_references:
    # the deadline must be derived from the instance-signed consent record and
    # clamped to the 90-day ceiling, which the store cannot do because it holds no
    # key.  Keeping a second implementation here would let the two disagree, which
    # is exactly the class of bug the signed-deadline change exists to remove.

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

def format_timestamp(timestamp: float) -> str:
    """ISO-8601 UTC timestamp with an explicit offset."""
    from datetime import datetime, timezone

    return datetime.fromtimestamp(timestamp, tz=timezone.utc).isoformat()


def parse_timestamp(value: str) -> float | None:
    """Epoch seconds for an ISO-8601 string, or ``None`` when unparseable."""
    from datetime import datetime, timezone

    text = str(value).strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.timestamp()


